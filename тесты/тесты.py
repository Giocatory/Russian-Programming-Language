def компилировать_и_запустить(код: str):
    л = Лексер(код); т = л.токенизировать()
    п = Парсер(т);   а = п.разобрать_файл()
    г = ГенераторRust(); rust = г.генерировать(а)
    with tempfile.NamedTemporaryFile(suffix='.rs', mode='w',
                                     delete=False, encoding='utf-8') as f:
        f.write(rust); rs = f.name
    try:
        rc = subprocess.run(
            ['rustc', rs, '-o', '/tmp/_сбк_тест',
             '--edition', '2021', '-A', 'warnings'],
            capture_output=True, text=True, timeout=30)
        if rc.returncode != 0:
            return None, rc.stderr[:300]
        out = subprocess.run(['/tmp/_сбк_тест'],
                             capture_output=True, text=True, timeout=5)
        return out.stdout.strip(), None
    finally:
        os.unlink(rs)


def тест(название, код, ожидается=None, содержит=None, должен_упасть=False):
    global пройдено, провалено
    print(f'  {СИН}•{СБР} {название}... ', end='', flush=True)
    try:
        вывод, ошибка = компилировать_и_запустить(код)
        if должен_упасть:
            print(f'{КРА}ПРОВАЛ{СБР} (ожидалась ошибка компиляции)')
            провалено += 1; return
        if ошибка:
            print(f'{КРА}ПРОВАЛ{СБР} (rustc: {ошибка[:80]})')
            провалено += 1; return
        if ожидается is not None:
            ок = вывод == ожидается.strip()
        elif содержит is not None:
            ок = содержит in вывод
        else:
            ок = True
        if ок:
            print(f'{ЗЕЛ}OK{СБР}')
            пройдено += 1
        else:
            print(f'{КРА}ПРОВАЛ{СБР}')
            print(f'    Ожидалось: {(ожидается or содержит)!r}')
            print(f'    Получено:  {вывод!r}')
            провалено += 1
    except (ОшибкаЛексера, ОшибкаПарсера) as e:
        if должен_упасть:
            print(f'{ЗЕЛ}OK{СБР} (ожидаемая ошибка)'); пройдено += 1
        else:
            print(f'{КРА}ПРОВАЛ{СБР} ({e})'); провалено += 1
    except Exception as e:
        print(f'{КРА}ПРОВАЛ{СБР} (исключение: {e})'); провалено += 1


