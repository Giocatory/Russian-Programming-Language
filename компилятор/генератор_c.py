# -*- coding: utf-8 -*-
"""
Генератор C-кода для языка Сибиряк
Транспилирует АСД в C-код, который затем компилируется GCC
"""

from аст import *
from typing import List, Dict, Set, Optional
import io


class ОшибкаГенератора(Exception):
    pass


# Маппинг встроенных пакетов Сибиряка → C-заголовки
ПАКЕТЫ_В_C = {
    'фмт': '#include <stdio.h>\n#include <string.h>',
    'математика': '#include <math.h>',
    'ос': '#include <stdlib.h>\n#include <unistd.h>',
    'время': '#include <time.h>',
    'строки': '#include <string.h>',
    'случай': '#include <stdlib.h>\n#include <time.h>',
}

# Маппинг типов Сибиряка → C
ТИПЫ_C = {
    'цел': 'long',
    'цел8': 'int8_t',
    'цел16': 'int16_t',
    'цел32': 'int32_t',
    'цел64': 'int64_t',
    'байт': 'uint8_t',
    'руна': 'int32_t',
    'вещ32': 'float',
    'вещ64': 'double',
    'строка': 'const char*',
    'булево': 'int',
    'любой': 'void*',
    'ошибка': 'const char*',
}

ПРОЛОГ = '''/* Сгенерировано компилятором Сибиряк */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <math.h>

/* ─── Рантайм Сибиряк ─── */
typedef const char* строка_т;
typedef int булево_т;
#define истина 1
#define ложь  0
#define ноль  NULL

/* Динамический срез */
typedef struct {
    void*  данные;
    long   длина;
    long   ёмкость;
    size_t размер_эл;
} _Срез;

static _Срез _создать_срез(size_t размер_эл, long ёмкость) {
    _Срез с;
    с.размер_эл = размер_эл;
    с.ёмкость   = ёмкость > 0 ? ёмкость : 8;
    с.длина     = 0;
    с.данные    = malloc(с.ёмкость * размер_эл);
    return с;
}

static _Срез _добавить_срез(_Срез с, void* эл) {
    if (с.длина >= с.ёмкость) {
        с.ёмкость *= 2;
        с.данные   = realloc(с.данные, с.ёмкость * с.размер_эл);
    }
    memcpy((char*)с.данные + с.длина * с.размер_эл, эл, с.размер_эл);
    с.длина++;
    return с;
}

#define _ДЛИНА_СРЕЗА(с)  ((с).длина)
#define _ЭЛ_СРЕЗА(с, тип, i) (((тип*)(с).данные)[i])

/* Паника */
static void _паника(const char* сообщение) {
    fprintf(stderr, "паника: %s\\n", сообщение);
    exit(1);
}

/* Конвертация чисел в строку */
static char _буф_числа[64];
static const char* _цел_в_стр(long n) {
    snprintf(_буф_числа, sizeof(_буф_числа), "%ld", n);
    return _буф_числа;
}
static const char* _вещ_в_стр(double n) {
    snprintf(_буф_числа, sizeof(_буф_числа), "%g", n);
    return _буф_числа;
}

/* Конкатенация строк */
static char* _конкат(const char* а, const char* б) {
    size_t la = strlen(а), lb = strlen(б);
    char* рез = malloc(la + lb + 1);
    memcpy(рез, а, la);
    memcpy(рез + la, б, lb + 1);
    return рез;
}

/* Сравнение строк */
static int _стр_равно(const char* а, const char* б) { return strcmp(а, б) == 0; }
static int _стр_меньше(const char* а, const char* б) { return strcmp(а, б) < 0; }

'''


class ГенераторC:
    def __init__(self):
        self.вывод = io.StringIO()
        self.отступ = 0
        self.импорты: Set[str] = set()
        self.объявленные_типы: Dict[str, str] = {}
        self.структуры: List[str] = []
        self.функции: List[str] = []
        self.глобальные: List[str] = []
        self.пакет = ''
        # Контекст: текущий тип возврата функции
        self.тип_возврата: List[List[ЛюбойТип]] = []

    def генерировать(self, программа: ФайлПрограммы) -> str:
        self.пакет = программа.пакет

        # Обработка импортов
        for имп in программа.импорты:
            for спек in имп.спецификации:
                if спек.путь in ПАКЕТЫ_В_C:
                    self.импорты.add(ПАКЕТЫ_В_C[спек.путь])

        # Предварительный проход: структуры и типы
        for объявл in программа.объявления:
            if isinstance(объявл, ОбъявлениеСтруктуры):
                self.объявить_структуру(объявл)

        # Генерация функций
        функции_код = []
        глобальные_код = []

        for объявл in программа.объявления:
            if isinstance(объявл, ОбъявлениеФункции):
                функции_код.append(self.генерировать_функцию(объявл))
            elif isinstance(объявл, ОбъявлениеПеременной):
                глобальные_код.append(self.генерировать_глобальную_переменную(объявл))
            elif isinstance(объявл, ОбъявлениеКонстанты):
                глобальные_код.append(self.генерировать_константу(объявл))

        # Сборка итогового файла
        результат = []
        результат.append(ПРОЛОГ)

        for имп in sorted(self.импорты):
            результат.append(имп)
        результат.append('')

        for стр in self.структуры:
            результат.append(стр)
        результат.append('')

        for стр in глобальные_код:
            результат.append(стр)

        for код in функции_код:
            результат.append(код)
            результат.append('')

        return '\n'.join(результат)

    # ─── Типы ────────────────────────────────────────────────────────────────

    def тип_в_c(self, тип: ЛюбойТип) -> str:
        if isinstance(тип, ПростойТип):
            return ТИПЫ_C.get(тип.имя, тип.имя)
        if isinstance(тип, СрезТип):
            return '_Срез'
        if isinstance(тип, МассивТип):
            эл = self.тип_в_c(тип.элемент)
            return f'{эл}*'
        if isinstance(тип, УказательТип):
            return f'{self.тип_в_c(тип.база)}*'
        if isinstance(тип, КартаТип):
            return 'void*'  # Упрощённо
        if isinstance(тип, ФункцияТип):
            return 'void*'
        if isinstance(тип, КаналТип):
            return 'void*'
        return 'void'

    def объявить_структуру(self, объявл: ОбъявлениеСтруктуры):
        код = f'typedef struct {{\n'
        for поле in объявл.тип.поля:
            c_тип = self.тип_в_c(поле.тип)
            for имя in поле.имена:
                код += f'    {c_тип} {self.безопасное_имя(имя)};\n'
        код += f'}} {объявл.имя};\n'
        self.структуры.append(код)

    # ─── Функции ─────────────────────────────────────────────────────────────

    def генерировать_функцию(self, объявл: ОбъявлениеФункции) -> str:
        вывод = io.StringIO()

        # Определение типа возврата
        if not объявл.результаты:
            тип_рез = 'void'
        elif len(объявл.результаты) == 1:
            тип_рез = self.тип_в_c(объявл.результаты[0])
        else:
            # Множественный возврат — через структуру
            имя_стр = f'_Рез_{объявл.имя}'
            код_стр = f'typedef struct {{\n'
            for i, рез in enumerate(объявл.результаты):
                код_стр += f'    {self.тип_в_c(рез)} _р{i};\n'
            код_стр += f'}} {имя_стр};\n'
            self.структуры.append(код_стр)
            тип_рез = имя_стр

        # Параметры
        параметры_c = []
        if объявл.получатель:
            рец = объявл.получатель
            c_тип = self.тип_в_c(рец.тип)
            имя = рец.имена[0] if рец.имена else '_сам'
            параметры_c.append(f'{c_тип}* {self.безопасное_имя(имя)}')

        for пар in объявл.параметры:
            c_тип = self.тип_в_c(пар.тип)
            if пар.вариадик:
                # вариадик через срез
                c_тип = '_Срез'
            if пар.имена:
                for имя in пар.имена:
                    параметры_c.append(f'{c_тип} {self.безопасное_имя(имя)}')
            else:
                параметры_c.append(c_тип)

        имя_c = 'main' if объявл.имя == 'Главная' else self.безопасное_имя(объявл.имя)
        if объявл.имя == 'Главная':
            тип_рез = 'int'

        вывод.write(f'{тип_рез} {имя_c}({", ".join(параметры_c) or "void"}) {{\n')

        # Тело
        self.тип_возврата.append(объявл.результаты)
        if объявл.тело:
            for оп in объявл.тело.операторы:
                вывод.write(self.генерировать_оператор(оп, отступ=1))
        self.тип_возврата.pop()

        # main всегда возвращает 0
        if объявл.имя == 'Главная':
            вывод.write('    return 0;\n')

        вывод.write('}\n')
        return вывод.getvalue()

    # ─── Операторы ───────────────────────────────────────────────────────────

    def отст(self, n: int) -> str:
        return '    ' * n

    def генерировать_оператор(self, оп: ЛюбойОператор, отступ=0) -> str:
        о = self.отст(отступ)

        if isinstance(оп, ОператорВозврата):
            if not оп.значения:
                return f'{о}return;\n'
            elif len(оп.значения) == 1:
                return f'{о}return {self.генерировать_выражение(оп.значения[0])};\n'
            else:
                # Множественный возврат
                рез_тип = f'_Рез_???'
                элементы = ', '.join(self.генерировать_выражение(в) for в in оп.значения)
                return f'{о}return ({рез_тип}){{{элементы}}};\n'

        if isinstance(оп, ОператорВыражения):
            return f'{о}{self.генерировать_выражение(оп.выражение)};\n'

        if isinstance(оп, ОператорКороткогоОбъявления):
            if len(оп.имена) == 1 and len(оп.значения) == 1:
                знач = self.генерировать_выражение(оп.значения[0])
                имя = self.безопасное_имя(оп.имена[0])
                return f'{о}__auto_type {имя} = {знач};\n'
            else:
                результат = ''
                for i, (имя, знач) in enumerate(zip(оп.имена, оп.значения)):
                    if имя != '_':
                        v = self.генерировать_выражение(знач)
                        результат += f'{о}__auto_type {self.безопасное_имя(имя)} = {v};\n'
                return результат

        if isinstance(оп, ОператорПрисваивания):
            if len(оп.цели) == 1 and len(оп.значения) == 1:
                цель = self.генерировать_выражение(оп.цели[0])
                знач = self.генерировать_выражение(оп.значения[0])
                return f'{о}{цель} {оп.оператор} {знач};\n'
            результат = ''
            for цель, знач in zip(оп.цели, оп.значения):
                if not (isinstance(цель, Идентификатор) and цель.имя == '_'):
                    результат += f'{о}{self.генерировать_выражение(цель)} {оп.оператор} {self.генерировать_выражение(знач)};\n'
            return результат

        if isinstance(оп, ОператорИнкремента):
            # оп.оператор это '++' или '--'
            оператор = оп.оператор if len(оп.оператор) == 2 else '++'
            return f'{о}{self.генерировать_выражение(оп.выражение)}{оператор};\n'

        if isinstance(оп, ОбъявлениеПеременной):
            результат = ''
            for имя in оп.имена:
                if оп.тип:
                    c_тип = self.тип_в_c(оп.тип)
                    имя_c = self.безопасное_имя(имя)
                    if оп.значения:
                        для_имени = оп.значения[0] if len(оп.значения) == 1 else оп.значения[оп.имена.index(имя)]
                        результат += f'{о}{c_тип} {имя_c} = {self.генерировать_выражение(для_имени)};\n'
                    else:
                        результат += f'{о}{c_тип} {имя_c} = 0;\n'
                else:
                    if оп.значения:
                        знач = self.генерировать_выражение(оп.значения[0])
                        результат += f'{о}__auto_type {self.безопасное_имя(имя)} = {знач};\n'
            return результат

        if isinstance(оп, ОбъявлениеКонстанты):
            результат = ''
            for имя, знач in zip(оп.имена, оп.значения):
                c_тип = self.тип_в_c(оп.тип) if оп.тип else 'const long'
                результат += f'{о}{c_тип} {self.безопасное_имя(имя)} = {self.генерировать_выражение(знач)};\n'
            return результат

        if isinstance(оп, ОператорЕсли):
            результат = f'{о}if ({self.генерировать_выражение(оп.условие)}) {{\n'
            for ст in оп.тогда.операторы:
                результат += self.генерировать_оператор(ст, отступ + 1)
            результат += f'{о}}}'
            if оп.иначе:
                if isinstance(оп.иначе, ОператорЕсли):
                    результат += f' else {self.генерировать_оператор(оп.иначе, отступ).lstrip()}'
                    return результат
                else:
                    результат += f' else {{\n'
                    for ст in оп.иначе.операторы:
                        результат += self.генерировать_оператор(ст, отступ + 1)
                    результат += f'{о}}}'
            результат += '\n'
            return результат

        if isinstance(оп, ОператорДля):
            if оп.тип_цикла == 'бесконечный':
                результат = f'{о}while (1) {{\n'
                for ст in оп.тело.операторы:
                    результат += self.генерировать_оператор(ст, отступ + 1)
                результат += f'{о}}}\n'
                return результат

            if оп.тип_цикла == 'диапазон':
                # for k, v := range arr
                итер = self.генерировать_выражение(оп.итерируемое)
                ключ = self.безопасное_имя(оп.ключ) if оп.ключ and оп.ключ != '_' else '_сбк_к'
                знач = self.безопасное_имя(оп.значение) if оп.значение and оп.значение != '_' else '_сбк_в'
                результат = f'{о}for (long {ключ} = 0; {ключ} < _ДЛИНА_СРЕЗА({итер}); {ключ}++) {{\n'
                # TODO: тип элемента из контекста
                результат += f'{о}    __auto_type {знач} = _ЭЛ_СРЕЗА({итер}, long, {ключ});\n'
                for ст in оп.тело.операторы:
                    результат += self.генерировать_оператор(ст, отступ + 1)
                результат += f'{о}}}\n'
                return результат

            # Обычный for
            инит = ''
            if оп.инициализация:
                инит = self.генерировать_оператор(оп.инициализация, 0).strip().rstrip(';')
            усл = self.генерировать_выражение(оп.условие) if оп.условие else '1'
            пост = ''
            if оп.пост:
                пост = self.генерировать_оператор(оп.пост, 0).strip().rstrip(';')

            результат = f'{о}for ({инит}; {усл}; {пост}) {{\n'
            for ст in оп.тело.операторы:
                результат += self.генерировать_оператор(ст, отступ + 1)
            результат += f'{о}}}\n'
            return результат

        if isinstance(оп, ОператорПереключить):
            # Если выражения в case не являются константами → if-else цепочка
            если_цепочка = (оп.выражение is None or
                any(len(с.выражения) > 0 and any(
                    not isinstance(в, (ЛитералЦелого, ЛитералРуны))
                    for в in с.выражения) for с in оп.случаи))

            if если_цепочка:
                # Генерируем if-else if-else
                выр_сравн = self.генерировать_выражение(оп.выражение) if оп.выражение else None
                результат = ''
                первый = True
                for случай in оп.случаи:
                    if not случай.выражения:
                        результат += f'{о}else {{\n'
                    else:
                        условия = []
                        for выр_сл in случай.выражения:
                            с = self.генерировать_выражение(выр_сл)
                            if выр_сравн:
                                условия.append(f'({выр_сравн} == {с})')
                            else:
                                условия.append(с)
                        усл = ' || '.join(условия)
                        кл = 'if' if первый else 'else if'
                        результат += f'{о}{кл} ({усл}) {{\n'
                    первый = False
                    for ст in случай.тело:
                        результат += self.генерировать_оператор(ст, отступ + 1)
                    результат += f'{о}}}\n'
                return результат
            else:
                выр = self.генерировать_выражение(оп.выражение)
                результат = f'{о}switch ({выр}) {{\n'
                for случай in оп.случаи:
                    if случай.выражения:
                        for выр_сл in случай.выражения:
                            результат += f'{о}case {self.генерировать_выражение(выр_сл)}:\n'
                    else:
                        результат += f'{о}default:\n'
                    for ст in случай.тело:
                        результат += self.генерировать_оператор(ст, отступ + 1)
                    результат += f'{о}    break;\n'
                результат += f'{о}}}\n'
                return результат

        if isinstance(оп, ОператорПрервать):
            return f'{о}break;\n'

        if isinstance(оп, ОператорПродолжить):
            return f'{о}continue;\n'

        if isinstance(оп, ОператорПерейти):
            return f'{о}goto {self.безопасное_имя(оп.метка)};\n'

        if isinstance(оп, ОператорМетки):
            вн = self.генерировать_оператор(оп.оператор, отступ)
            return f'{о}{self.безопасное_имя(оп.имя)}:\n{вн}'

        if isinstance(оп, БлокОператоров):
            результат = f'{о}{{\n'
            for ст in оп.операторы:
                результат += self.генерировать_оператор(ст, отступ + 1)
            результат += f'{о}}}\n'
            return результат

        if isinstance(оп, ОператорОтложить):
            # Упрощённо — выполняем сразу (полный defer требует longjmp/уборки)
            return f'{о}/* отложить */ {self.генерировать_выражение(оп.вызов)};\n'

        if isinstance(оп, ОператорГорутины):
            # Упрощённо — синхронный вызов
            return f'{о}/* горутина */ {self.генерировать_выражение(оп.вызов)};\n'

        return f'{о}/* неизвестный оператор */\n'

    def генерировать_глобальную_переменную(self, объявл: ОбъявлениеПеременной) -> str:
        результат = ''
        for имя in объявл.имена:
            c_тип = self.тип_в_c(объявл.тип) if объявл.тип else 'long'
            имя_c = self.безопасное_имя(имя)
            if объявл.значения:
                знач = self.генерировать_выражение(объявл.значения[0])
                результат += f'static {c_тип} {имя_c} = {знач};\n'
            else:
                результат += f'static {c_тип} {имя_c} = 0;\n'
        return результат

    def генерировать_константу(self, объявл: ОбъявлениеКонстанты) -> str:
        результат = ''
        for имя, знач in zip(объявл.имена, объявл.значения):
            результат += f'#define {self.безопасное_имя(имя)} ({self.генерировать_выражение(знач)})\n'
        return результат

    # ─── Выражения ───────────────────────────────────────────────────────────

    def генерировать_выражение(self, выр: ЛюбойВыражение) -> str:
        if isinstance(выр, ЛитералЦелого):
            return str(выр.значение)

        if isinstance(выр, ЛитералВещественного):
            return str(выр.значение)

        if isinstance(выр, ЛитералСтроки):
            # Экранируем строку для C
            экр = выр.значение.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t')
            return f'"{экр}"'

        if isinstance(выр, ЛитералРуны):
            return f"'{выр.значение}'"

        if isinstance(выр, ЛитералИстина):
            return '1'

        if isinstance(выр, ЛитералЛожь):
            return '0'

        if isinstance(выр, ЛитералНоль):
            return 'NULL'

        if isinstance(выр, Идентификатор):
            # Встроенные функции
            встроенные = {
                'длина': '_ДЛИНА_СРЕЗА',
                'паника': '_паника',
            }
            return встроенные.get(выр.имя, self.безопасное_имя(выр.имя))

        if isinstance(выр, БинарноеВыражение):
            л = self.генерировать_выражение(выр.левое)
            п = self.генерировать_выражение(выр.правое)
            # Для строк: конкатенация +
            return f'({л} {выр.оператор} {п})'

        if isinstance(выр, УнарноеВыражение):
            оп = выр.оператор
            if оп == '!':
                return f'(!{self.генерировать_выражение(выр.операнд)})'
            return f'({оп}{self.генерировать_выражение(выр.операнд)})'

        if isinstance(выр, ВызовФункции):
            return self.генерировать_вызов(выр)

        if isinstance(выр, ДоступКПолю):
            объект = self.генерировать_выражение(выр.объект)
            # Указатель или значение
            return f'{объект}.{self.безопасное_имя(выр.поле)}'

        if isinstance(выр, Индексирование):
            объект = self.генерировать_выражение(выр.объект)
            индекс = self.генерировать_выражение(выр.индекс)
            return f'{объект}[{индекс}]'

        if isinstance(выр, Срезание):
            # Упрощённо
            объект = self.генерировать_выражение(выр.объект)
            низ = self.генерировать_выражение(выр.низ) if выр.низ else '0'
            return f'({объект} + {низ})'

        if isinstance(выр, ПреобразованиеТипа):
            c_тип = self.тип_в_c(выр.тип)
            операнд = self.генерировать_выражение(выр.выражение)
            return f'(({c_тип}){операнд})'

        if isinstance(выр, ЛитералСтруктуры):
            c_тип = self.тип_в_c(выр.тип) if выр.тип else ''
            поля = []
            for поле in выр.поля:
                поля.append(f'.{self.безопасное_имя(поле.ключ)} = {self.генерировать_выражение(поле.значение)}' if поле.ключ else self.генерировать_выражение(поле.значение))
            return f'({c_тип}){{{", ".join(поля)}}}'

        if isinstance(выр, ВыражениеКанала):
            # Упрощённо
            return f'/* <-канал */'

        if isinstance(выр, АнонимнаяФункция):
            return '/* анон. функция */'

        return '0 /* неизвестное выражение */'

    def генерировать_вызов(self, выр: ВызовФункции) -> str:
        # Встроенные функции
        if isinstance(выр.функция, Идентификатор):
            имя = выр.функция.имя

            if имя == 'печатьф':
                # Аналог fmt.Printf / fmt.Println
                аргументы = ', '.join(self.генерировать_выражение(а) for а in выр.аргументы)
                return f'printf({аргументы})'

            if имя == 'печать':
                # Аналог fmt.Println — печать с переводом строки
                if not выр.аргументы:
                    return 'printf("\\n")'
                части = []
                форматы = []
                for а in выр.аргументы:
                    форматы.append('%s')
                    части.append(f'({self.генерировать_выражение(а)})')
                # Упрощённо — предполагаем строки
                аргументы = ', '.join(части)
                формат = ' '.join(форматы) + '\\n'
                return f'printf("{формат}", {аргументы})'

            if имя == 'печатьс':
                аргументы = ', '.join(self.генерировать_выражение(а) for а in выр.аргументы)
                return f'fprintf(stderr, {аргументы})'

            if имя == 'длина':
                if выр.аргументы:
                    а = self.генерировать_выражение(выр.аргументы[0])
                    return f'_ДЛИНА_СРЕЗА({а})'
                return '0'

            if имя == 'создать':
                # создать([]цел, 0, 10) → _создать_срез(sizeof(long), 10)
                if len(выр.аргументы) >= 2:
                    ёмк = self.генерировать_выражение(выр.аргументы[-1])
                    return f'_создать_срез(sizeof(long), {ёмк})'
                return '_создать_срез(sizeof(long), 8)'

            if имя == 'добавить':
                if len(выр.аргументы) >= 2:
                    срез = self.генерировать_выражение(выр.аргументы[0])
                    эл = self.генерировать_выражение(выр.аргументы[1])
                    return f'_добавить_срез({срез}, &({эл}))'
                return '/* добавить */'

            if имя == 'паника':
                аргументы = ', '.join(self.генерировать_выражение(а) for а in выр.аргументы)
                return f'_паника({аргументы})'

            if имя == 'новый':
                if выр.аргументы and isinstance(выр.аргументы[0], Идентификатор):
                    тип = выр.аргументы[0].имя
                    return f'calloc(1, sizeof({тип}))'

        # Метод через точку
        if isinstance(выр.функция, ДоступКПолю):
            # Маппинг методов стандартной библиотеки
            объект = self.генерировать_выражение(выр.функция.объект)
            метод = выр.функция.поле
            аргументы = ', '.join(self.генерировать_выражение(а) for а in выр.аргументы)

            # фмт.Печать → printf
            if isinstance(выр.функция.объект, Идентификатор):
                пакет = выр.функция.объект.имя
                if пакет == 'фмт':
                    if метод in ('Печать', 'Вывести'):
                        if аргументы:
                            return f'printf("%s\\n", {аргументы})'
                        return 'printf("\\n")'
                    if метод in ('ПечатьФ', 'ВыводитьФ', 'Форматировать'):
                        return f'printf({аргументы})'
                    if метод in ('Скан', 'Считать'):
                        return f'scanf({аргументы})'
                if пакет == 'ос':
                    if метод == 'Выход':
                        return f'exit({аргументы})'
                    if метод == 'Аргументы':
                        return 'NULL /* ос.Аргументы */'
                if пакет == 'математика':
                    матем_функции = {
                        'Корень': 'sqrt', 'Степень': 'pow', 'Абс': 'fabs',
                        'Синус': 'sin', 'Косинус': 'cos', 'Тангенс': 'tan',
                        'Логарифм': 'log', 'Логарифм10': 'log10',
                        'Пол': 'floor', 'Потолок': 'ceil', 'Округл': 'round',
                        'Макс': 'fmax', 'Мин': 'fmin',
                    }
                    if метод in матем_функции:
                        return f'{матем_функции[метод]}({аргументы})'

            return f'{объект}.{self.безопасное_имя(метод)}({аргументы})'

        # Обычный вызов функции
        функция = self.генерировать_выражение(выр.функция)
        аргументы = ', '.join(self.генерировать_выражение(а) for а in выр.аргументы)
        return f'{функция}({аргументы})'

