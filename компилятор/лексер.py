class ОшибкаЛексера(Exception):
    def __init__(self, сообщение, строка, столбец):
        super().__init__(f"Ошибка лексера в строке {строка}, столбец {столбец}: {сообщение}")
        self.строка = строка
        self.столбец = столбец


class Лексер:
    def __init__(self, исходник: str):
        self.исходник = исходник
        self.позиция = 0
        self.строка = 1
        self.столбец = 1
        self.токены: List[Токен] = []

    def текущий(self) -> Optional[str]:
        if self.позиция < len(self.исходник):
            return self.исходник[self.позиция]
        return None

    def следующий(self) -> Optional[str]:
        if self.позиция + 1 < len(self.исходник):
            return self.исходник[self.позиция + 1]
        return None

    def продвинуть(self) -> str:
        сим = self.исходник[self.позиция]
        self.позиция += 1
        if сим == '\n':
            self.строка += 1
            self.столбец = 1
        else:
            self.столбец += 1
        return сим

    def добавить_токен(self, тип: ТипТокена, значение: str):
        self.токены.append(Токен(тип, значение, self.строка, self.столбец))

    def пропустить_пробелы(self):
        while self.текущий() and self.текущий() in ' \t\r':
            self.продвинуть()

    def читать_комментарий(self):
        # Однострочный комментарий //
        while self.текущий() and self.текущий() != '\n':
            self.продвинуть()

    def читать_блочный_комментарий(self):
        # Блочный комментарий /* */
        while self.текущий():
            if self.текущий() == '*' and self.следующий() == '/':
                self.продвинуть()
                self.продвинуть()
                return
            self.продвинуть()
        raise ОшибкаЛексера("Незакрытый блочный комментарий", self.строка, self.столбец)

    def читать_строку(self) -> str:
        результат = ''
        self.продвинуть()  # открывающая "
        while self.текущий() and self.текущий() != '"':
            if self.текущий() == '\\':
                self.продвинуть()
                escape = self.продвинуть()
                escape_map = {'n': '\n', 't': '\t', 'r': '\r', '\\': '\\', '"': '"', '0': '\0'}
                результат += escape_map.get(escape, escape)
            else:
                результат += self.продвинуть()
        if not self.текущий():
            raise ОшибкаЛексера("Незакрытая строка", self.строка, self.столбец)
        self.продвинуть()  # закрывающая "
        return результат

    def читать_сырую_строку(self) -> str:
        результат = ''
        self.продвинуть()  # открывающий `
        while self.текущий() and self.текущий() != '`':
            результат += self.продвинуть()
        if not self.текущий():
            raise ОшибкаЛексера("Незакрытая сырая строка", self.строка, self.столбец)
        self.продвинуть()  # закрывающий `
        return результат

    def читать_руну(self) -> str:
        результат = ''
        self.продвинуть()  # открывающий '
        if self.текущий() == '\\':
            self.продвинуть()
            escape = self.продвинуть()
            escape_map = {'n': '\n', 't': '\t', 'r': '\r', '\\': '\\', "'": "'"}
            результат = escape_map.get(escape, escape)
        else:
            результат = self.продвинуть()
        if self.текущий() != "'":
            raise ОшибкаЛексера("Незакрытый символ руны", self.строка, self.столбец)
        self.продвинуть()
        return результат

    def читать_число(self) -> tuple:
        результат = ''
        является_вещ = False

        # Шестнадцатеричные
        if self.текущий() == '0' and self.следующий() in ('x', 'X'):
            результат += self.продвинуть()
            результат += self.продвинуть()
            while self.текущий() and self.текущий() in '0123456789abcdefABCDEF_':
                результат += self.продвинуть()
            return (ТипТокена.ЛИТ_ЦЕЛОЕ, результат)

        while self.текущий() and (self.текущий().isdigit() or self.текущий() == '_'):
            результат += self.продвинуть()

        if self.текущий() == '.' and self.следующий() and self.следующий().isdigit():
            является_вещ = True
            результат += self.продвинуть()
            while self.текущий() and (self.текущий().isdigit() or self.текущий() == '_'):
                результат += self.продвинуть()

        if self.текущий() in ('e', 'E'):
            является_вещ = True
            результат += self.продвинуть()
            if self.текущий() in ('+', '-'):
                результат += self.продвинуть()
            while self.текущий() and self.текущий().isdigit():
                результат += self.продвинуть()

        тип = ТипТокена.ЛИТ_ВЕЩЕСТВЕННОЕ if является_вещ else ТипТокена.ЛИТ_ЦЕЛОЕ
        return (тип, результат)

    def является_идент_символом(self, сим: str, первый=False) -> bool:
        """Проверяет, может ли символ быть частью идентификатора (включая кириллицу)"""
        if первый:
            return сим.isalpha() or сим == '_' or ('\u0400' <= сим <= '\u04FF')
        return сим.isalnum() or сим == '_' or ('\u0400' <= сим <= '\u04FF')

    def читать_идентификатор(self) -> str:
        результат = ''
        while self.текущий() and self.является_идент_символом(self.текущий()):
            результат += self.продвинуть()
        return результат

    def токенизировать(self) -> List[Токен]:
        # Токены после которых автоматически вставляется ;
        авто_точка_с_зап = {
            ТипТокена.ИДЕНТИФИКАТОР, ТипТокена.ЛИТ_ЦЕЛОЕ, ТипТокена.ЛИТ_ВЕЩЕСТВЕННОЕ,
            ТипТокена.ЛИТ_СТРОКА, ТипТокена.ЛИТ_РУНА, ТипТокена.ИСТИНА, ТипТокена.ЛОЖЬ,
            ТипТокена.НОЛЬ, ТипТокена.ИНКРЕМЕНТ, ТипТокена.ДЕКРЕМЕНТ,
            ТипТокена.СКОБКА_П, ТипТокена.КВ_СКОБКА_П, ТипТокена.ФИГ_СКОБКА_П,
            ТипТокена.ВОЗВРАТ, ТипТокена.ПРЕРВАТЬ, ТипТокена.ПРОДОЛЖИТЬ, ТипТокена.ПЕРЕЙТИ,
            ТипТокена.ЦЕЛ, ТипТокена.ЦЕЛ8, ТипТокена.ЦЕЛ16, ТипТокена.ЦЕЛ32, ТипТокена.ЦЕЛ64,
            ТипТокена.БАЙТ, ТипТокена.РУНА, ТипТокена.ВЕЩ32, ТипТокена.ВЕЩ64,
            ТипТокена.СТРОКА, ТипТокена.БУЛЕВО,
        }
        последний_тип = None

        while self.текущий():
            # Пробелы
            if self.текущий() in ' \t\r':
                self.пропустить_пробелы()
                continue

            # Новая строка — автоточка с запятой
            if self.текущий() == '\n':
                if последний_тип in авто_точка_с_зап:
                    self.добавить_токен(ТипТокена.ТОЧКА_С_ЗАП, ';')
                self.продвинуть()
                continue

            сим = self.текущий()

            # Комментарии
            if сим == '/' and self.следующий() == '/':
                self.продвинуть(); self.продвинуть()
                self.читать_комментарий()
                continue
            if сим == '/' and self.следующий() == '*':
                self.продвинуть(); self.продвинуть()
                self.читать_блочный_комментарий()
                continue

            # Строки
            if сим == '"':
                значение = self.читать_строку()
                self.добавить_токен(ТипТокена.ЛИТ_СТРОКА, значение)
                последний_тип = ТипТокена.ЛИТ_СТРОКА
                continue
            if сим == '`':
                значение = self.читать_сырую_строку()
                self.добавить_токен(ТипТокена.ЛИТ_СТРОКА, значение)
                последний_тип = ТипТокена.ЛИТ_СТРОКА
                continue
            if сим == "'":
                значение = self.читать_руну()
                self.добавить_токен(ТипТокена.ЛИТ_РУНА, значение)
                последний_тип = ТипТокена.ЛИТ_РУНА
                continue

            # Числа
            if сим.isdigit():
                тип, значение = self.читать_число()
                self.добавить_токен(тип, значение)
                последний_тип = тип
                continue

            # Идентификаторы и ключевые слова
            if self.является_идент_символом(сим, первый=True):
                значение = self.читать_идентификатор()
                тип = КЛЮЧЕВЫЕ_СЛОВА.get(значение, ТипТокена.ИДЕНТИФИКАТОР)
                self.добавить_токен(тип, значение)
                последний_тип = тип
                continue

            # Операторы и разделители
            self.продвинуть()
            оператор_тип = None

            if сим == '+':
                if self.текущий() == '+':
                    self.продвинуть(); оператор_тип = ТипТокена.ИНКРЕМЕНТ
                elif self.текущий() == '=':
                    self.продвинуть(); оператор_тип = ТипТокена.ПЛЮС_РАВНО
                else:
                    оператор_тип = ТипТокена.ПЛЮС
            elif сим == '-':
                if self.текущий() == '-':
                    self.продвинуть(); оператор_тип = ТипТокена.ДЕКРЕМЕНТ
                elif self.текущий() == '=':
                    self.продвинуть(); оператор_тип = ТипТокена.МИНУС_РАВНО
                else:
                    оператор_тип = ТипТокена.МИНУС
            elif сим == '*':
                if self.текущий() == '=':
                    self.продвинуть(); оператор_тип = ТипТокена.УМНОЖИТЬ_РАВНО
                else:
                    оператор_тип = ТипТокена.УМНОЖИТЬ
            elif сим == '/':
                if self.текущий() == '=':
                    self.продвинуть(); оператор_тип = ТипТокена.ДЕЛИТЬ_РАВНО
                else:
                    оператор_тип = ТипТокена.ДЕЛИТЬ
            elif сим == '%':
                if self.текущий() == '=':
                    self.продвинуть(); оператор_тип = ТипТокена.ОСТАТОК_РАВНО
                else:
                    оператор_тип = ТипТокена.ОСТАТОК
            elif сим == '&':
                if self.текущий() == '&':
                    self.продвинуть(); оператор_тип = ТипТокена.ЛЛОГИ
                elif self.текущий() == '=':
                    self.продвинуть(); оператор_тип = ТипТокена.И_РАВНО
                elif self.текущий() == '^':
                    self.продвинуть()
                    if self.текущий() == '=':
                        self.продвинуть(); оператор_тип = ТипТокена.И_НЕ_РАВНО
                    else:
                        оператор_тип = ТипТокена.И_НЕ
                else:
                    оператор_тип = ТипТокена.И
            elif сим == '|':
                if self.текущий() == '|':
                    self.продвинуть(); оператор_тип = ТипТокена.ИЛИЛИ
                elif self.текущий() == '=':
                    self.продвинуть(); оператор_тип = ТипТокена.ИЛИ_РАВНО
                else:
                    оператор_тип = ТипТокена.ИЛИ
            elif сим == '^':
                if self.текущий() == '=':
                    self.продвинуть(); оператор_тип = ТипТокена.XOR_РАВНО
                else:
                    оператор_тип = ТипТокена.XOR
            elif сим == '<':
                if self.текущий() == '<':
                    self.продвинуть()
                    if self.текущий() == '=':
                        self.продвинуть(); оператор_тип = ТипТокена.ВЛЕВО_РАВНО
                    else:
                        оператор_тип = ТипТокена.ВЛЕВО
                elif self.текущий() == '=':
                    self.продвинуть(); оператор_тип = ТипТокена.МЕНЬШЕ_ИЛИ
                elif self.текущий() == '-':
                    self.продвинуть(); оператор_тип = ТипТокена.СТРЕЛКА_К
                else:
                    оператор_тип = ТипТокена.МЕНЬШЕ
            elif сим == '>':
                if self.текущий() == '>':
                    self.продвинуть()
                    if self.текущий() == '=':
                        self.продвинуть(); оператор_тип = ТипТокена.ВПРАВО_РАВНО
                    else:
                        оператор_тип = ТипТокена.ВПРАВО
                elif self.текущий() == '=':
                    self.продвинуть(); оператор_тип = ТипТокена.БОЛЬШЕ_ИЛИ
                else:
                    оператор_тип = ТипТокена.БОЛЬШЕ
            elif сим == '=':
                if self.текущий() == '=':
                    self.продвинуть(); оператор_тип = ТипТокена.РАВНО
                else:
                    оператор_тип = ТипТокена.ПРИСВОИТЬ
            elif сим == '!':
                if self.текущий() == '=':
                    self.продвинуть(); оператор_тип = ТипТокена.НЕ_РАВНО
                else:
                    оператор_тип = ТипТокена.НЕ
            elif сим == ':':
                if self.текущий() == '=':
                    self.продвинуть(); оператор_тип = ТипТокена.КОРОТКОЕ_ОБ
                else:
                    оператор_тип = ТипТокена.ДВОЕТОЧИЕ
            elif сим == '.':
                if self.текущий() == '.' and self.следующий() == '.':
                    self.продвинуть(); self.продвинуть(); оператор_тип = ТипТокена.ТРОЕТОЧИЕ
                else:
                    оператор_тип = ТипТокена.ТОЧКА
            elif сим == ',': оператор_тип = ТипТокена.ЗАПЯТАЯ
            elif сим == ';': оператор_тип = ТипТокена.ТОЧКА_С_ЗАП
            elif сим == '(': оператор_тип = ТипТокена.СКОБКА_Л
            elif сим == ')': оператор_тип = ТипТокена.СКОБКА_П
            elif сим == '[': оператор_тип = ТипТокена.КВ_СКОБКА_Л
            elif сим == ']': оператор_тип = ТипТокена.КВ_СКОБКА_П
            elif сим == '{': оператор_тип = ТипТокена.ФИГ_СКОБКА_Л
            elif сим == '}': оператор_тип = ТипТокена.ФИГ_СКОБКА_П
            else:
                raise ОшибкаЛексера(f"Неизвестный символ: {сим!r}", self.строка, self.столбец)

            if оператор_тип:
                # Для многосимвольных операторов используем правильную строку
                символ_оп = {
                    ТипТокена.ИНКРЕМЕНТ: '++', ТипТокена.ДЕКРЕМЕНТ: '--',
                    ТипТокена.РАВНО: '==', ТипТокена.НЕ_РАВНО: '!=',
                    ТипТокена.МЕНЬШЕ_ИЛИ: '<=', ТипТокена.БОЛЬШЕ_ИЛИ: '>=',
                    ТипТокена.ЛЛОГИ: '&&', ТипТокена.ИЛИЛИ: '||',
                    ТипТокена.КОРОТКОЕ_ОБ: ':=', ТипТокена.СТРЕЛКА_К: '<-',
                    ТипТокена.ТРОЕТОЧИЕ: '...',
                    ТипТокена.ПЛЮС_РАВНО: '+=', ТипТокена.МИНУС_РАВНО: '-=',
                    ТипТокена.УМНОЖИТЬ_РАВНО: '*=', ТипТокена.ДЕЛИТЬ_РАВНО: '/=',
                    ТипТокена.ОСТАТОК_РАВНО: '%=', ТипТокена.И_РАВНО: '&=',
                    ТипТокена.ИЛИ_РАВНО: '|=', ТипТокена.XOR_РАВНО: '^=',
                    ТипТокена.ВЛЕВО: '<<', ТипТокена.ВПРАВО: '>>',
                    ТипТокена.ВЛЕВО_РАВНО: '<<=', ТипТокена.ВПРАВО_РАВНО: '>>=',
                    ТипТокена.И_НЕ: '&^', ТипТокена.И_НЕ_РАВНО: '&^=',
                }.get(оператор_тип, сим)
                self.добавить_токен(оператор_тип, символ_оп)
                последний_тип = оператор_тип

        # Автоточка с запятой перед EOF
        if последний_тип in авто_точка_с_зап:
            self.добавить_токен(ТипТокена.ТОЧКА_С_ЗАП, ';')

        self.добавить_токен(ТипТокена.КОНЕЦ_ФАЙЛА, '')
        return self.токены
