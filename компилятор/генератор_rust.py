from аст import *
from typing import List, Dict, Set, Optional
import io


class ОшибкаГенератора(Exception):
    pass


# Маппинг типов Сибиряка → Rust
ТИПЫ_RUST = {
    'цел':    'i64',
    'цел8':   'i8',
    'цел16':  'i16',
    'цел32':  'i32',
    'цел64':  'i64',
    'байт':   'u8',
    'руна':   'char',
    'вещ32':  'f32',
    'вещ64':  'f64',
    'строка': 'String',
    'булево': 'bool',
    'любой':  'Box<dyn std::any::Any>',
    'ошибка': 'Box<dyn std::error::Error>',
}

# Маппинг пакетов Сибиряка
ПАКЕТЫ = {
    'фмт':       'fmt',
    'математика': 'std::f64',
    'ос':         'std::process',
    'строки':     'std::string',
}

ПРОЛОГ_RUST = '''// Сгенерировано компилятором Сибиряк → Rust
#![allow(non_snake_case, non_camel_case_types, unused_variables, dead_code, unused_mut)]
#![allow(unused_imports, clippy::all)]

use std::io::{self, Write};
use std::fmt;
use std::collections::HashMap;

// ─── Рантайм Сибиряк ────────────────────────────────────────────────────────

/// Динамический срез (аналог Go slice)
#[derive(Clone, Debug)]
pub struct Срез<T: Clone> {
    данные: Vec<T>,
}

impl<T: Clone> Срез<T> {
    pub fn новый() -> Self { Срез { данные: Vec::new() } }
    pub fn с_ёмкостью(ёмкость: usize) -> Self { Срез { данные: Vec::with_capacity(ёмкость) } }
    pub fn длина(&self) -> i64 { self.данные.len() as i64 }
    pub fn ёмкость(&self) -> i64 { self.данные.capacity() as i64 }
    pub fn добавить(&mut self, эл: T) { self.данные.push(эл); }
    pub fn получить(&self, i: i64) -> &T { &self.данные[i as usize] }
    pub fn установить(&mut self, i: i64, v: T) { self.данные[i as usize] = v; }
    pub fn срез(&self, от: i64, до: i64) -> Срез<T> {
        Срез { данные: self.данные[от as usize..до as usize].to_vec() }
    }
}

impl<T: Clone + fmt::Display> fmt::Display for Срез<T> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "[")?;
        for (i, v) in self.данные.iter().enumerate() {
            if i > 0 { write!(f, " ")?; }
            write!(f, "{}", v)?;
        }
        write!(f, "]")
    }
}

/// Паника — аварийный выход
#[cold]
pub fn паника(сообщение: &str) -> ! {
    eprintln!("паника: {}", сообщение);
    std::process::exit(1);
}

/// Печать без форматирования (аналог fmt.Println)
macro_rules! печать {
    () => { println!() };
    ($($arg:tt)*) => { println!("{}", format!($($arg)*)) };
}

/// Форматированная печать (аналог fmt.Printf)
macro_rules! печатьф {
    ($fmt:expr $(, $arg:expr)*) => {
        print!($fmt $(, $arg)*);
        let _ = io::stdout().flush();
    };
}

/// Печать в stderr
macro_rules! печатьс {
    ($fmt:expr $(, $arg:expr)*) => { eprint!($fmt $(, $arg)*); };
}

// ─── Встроенные функции ─────────────────────────────────────────────────────

fn длина_строки(с: &str) -> i64 { с.chars().count() as i64 }

'''


def _конвертировать_формат(fmt_строка: str) -> str:
    """Конвертирует Go format-строку в Rust format-строку"""
    import re
    # %d,%ld,%lld → {}  (целые)
    result = re.sub(r'%[-+]?\d*(?:l+)?[diouxX]', '{}', fmt_строка)
    # %f,%g,%e,%E → {}  (вещественные)
    result = re.sub(r'%[-+]?\d*(?:\.\d+)?[fgeEG]', '{}', result)
    # %s → {}
    result = re.sub(r'%[-+]?\d*s', '{}', result)
    # %v,%T → {}
    result = re.sub(r'%[vTp]', '{:?}', result)
    # %c → {}
    result = re.sub(r'%c', '{}', result)
    # %t → {}
    result = re.sub(r'%t', '{}', result)
    # %% → %
    result = result.replace('%%', '%')
    return result


class ГенераторRust:
    def __init__(self):
        self.структуры: List[str] = []
        self.функции: List[str] = []
        self.глобальные: List[str] = []
        self.импортированные_пакеты: Set[str] = set()
        self.пакет = ''
        # Стек типов возврата для текущей функции
        self.тип_возврата_стек: List[List] = []
        # Локальные переменные для вывода типов
        self.локальные_переменные: Dict[str, str] = {}
        # Имена структур для определения типов
        self.имена_структур: Set[str] = set()

    def генерировать(self, программа: ФайлПрограммы) -> str:
        self.пакет = программа.пакет

        for имп in программа.импорты:
            for спек in имп.спецификации:
                self.импортированные_пакеты.add(спек.путь)

        # Предварительный проход: собираем имена структур
        for объявл in программа.объявления:
            if isinstance(объявл, ОбъявлениеСтруктуры):
                self.имена_структур.add(объявл.имя)

        # Генерация структур
        for объявл in программа.объявления:
            if isinstance(объявл, ОбъявлениеСтруктуры):
                self.структуры.append(self.генерировать_структуру(объявл))
            elif isinstance(объявл, ОбъявлениеИнтерфейса):
                self.структуры.append(self.генерировать_интерфейс(объявл))

        # Глобальные константы и переменные
        for объявл in программа.объявления:
            if isinstance(объявл, ОбъявлениеКонстанты):
                self.глобальные.append(self.генерировать_глобальную_константу(объявл))
            elif isinstance(объявл, ОбъявлениеПеременной):
                self.глобальные.append(self.генерировать_глобальную_переменную_rust(объявл))

        # Генерация функций
        for объявл in программа.объявления:
            if isinstance(объявл, ОбъявлениеФункции):
                self.функции.append(self.генерировать_функцию(объявл))

        # Сборка
        части = [ПРОЛОГ_RUST]

        for глоб in self.глобальные:
            if глоб.strip():
                части.append(глоб)

        for стр in self.структуры:
            части.append(стр)

        for функ in self.функции:
            части.append(функ)

        return '\n'.join(части)

    # ─── Типы ────────────────────────────────────────────────────────────────

    def тип_в_rust(self, тип: ЛюбойТип, ссылка=False) -> str:
        if isinstance(тип, ПростойТип):
            r = ТИПЫ_RUST.get(тип.имя, тип.имя)
            return r
        if isinstance(тип, СрезТип):
            эл = self.тип_в_rust(тип.элемент)
            return f'Vec<{эл}>'
        if isinstance(тип, МассивТип):
            эл = self.тип_в_rust(тип.элемент)
            if isinstance(тип.размер, ЛитералЦелого):
                return f'[{эл}; {тип.размер.значение}]'
            return f'Vec<{эл}>'
        if isinstance(тип, УказательТип):
            база = self.тип_в_rust(тип.база)
            return f'Box<{база}>'
        if isinstance(тип, КартаТип):
            к = self.тип_в_rust(тип.ключ)
            в = self.тип_в_rust(тип.значение)
            return f'HashMap<{к}, {в}>'
        if isinstance(тип, ФункцияТип):
            params = ', '.join(self.тип_в_rust(п.тип) for п in тип.параметры)
            if тип.результаты:
                рез = self.тип_в_rust(тип.результаты[0])
                return f'fn({params}) -> {рез}'
            return f'fn({params})'
        if isinstance(тип, КаналТип):
            эл = self.тип_в_rust(тип.элемент)
            return f'std::sync::mpsc::Sender<{эл}>'
        return 'i64'

    def тип_возврата_rust(self, результаты: List) -> str:
        if not результаты:
            return ''
        if len(результаты) == 1:
            return f' -> {self.тип_в_rust(результаты[0])}'
        типы = ', '.join(self.тип_в_rust(р) for р in результаты)
        return f' -> ({типы})'

    # ─── Структуры ───────────────────────────────────────────────────────────

    def генерировать_структуру(self, объявл: ОбъявлениеСтруктуры) -> str:
        вывод = []
        вывод.append(f'#[derive(Clone, Debug, Default)]')
        вывод.append(f'pub struct {объявл.имя} {{')
        for поле in объявл.тип.поля:
            rust_тип = self.тип_в_rust(поле.тип)
            for имя in поле.имена:
                вывод.append(f'    pub {имя}: {rust_тип},')
        вывод.append('}')
        вывод.append('')

        # Генерируем impl с методами (будет заполнено позже)
        вывод.append(f'impl {объявл.имя} {{')
        вывод.append(f'    pub fn новый() -> Self {{ Self::default() }}')
        вывод.append('}')
        вывод.append('')
        return '\n'.join(вывод)

    def генерировать_интерфейс(self, объявл: ОбъявлениеИнтерфейса) -> str:
        вывод = []
        вывод.append(f'pub trait {объявл.имя} {{')
        for метод in объявл.тип.методы:
            params = ', '.join(
                f'{", ".join(п.имена) or "_"}: {self.тип_в_rust(п.тип)}'
                for п in метод.тип.параметры
            )
            рез = self.тип_возврата_rust(метод.тип.результаты)
            вывод.append(f'    fn {метод.имя}(&mut self, {params}){рез};')
        вывод.append('}')
        вывод.append('')
        return '\n'.join(вывод)

    # ─── Функции ─────────────────────────────────────────────────────────────

    def генерировать_функцию(self, объявл: ОбъявлениеФункции) -> str:
        вывод = io.StringIO()
        self.локальные_переменные = {}

        имя = 'main' if объявл.имя == 'Главная' else объявл.имя

        # Получатель метода
        получатель_str = ''
        if объявл.получатель:
            рец = объявл.получатель
            имя_рец = рец.имена[0] if рец.имена else 'self'
            тип_рец = self.тип_в_rust(рец.тип)
            получатель_str = f'({имя_рец}: &mut {тип_рец})'

        # Параметры
        params = []
        if получатель_str:
            params_str = получатель_str[1:-1]  # убрать скобки
        
        rust_params = []
        for пар in объявл.параметры:
            rust_тип = self.тип_в_rust(пар.тип)
            # Строки — берём &str для входных параметров
            if rust_тип == 'String':
                rust_тип = '&str'
            if пар.вариадик:
                rust_тип = f'&[{rust_тип}]'
            if пар.имена:
                for имя_п in пар.имена:
                    rust_params.append(f'mut {имя_п}: {rust_тип}')
                    self.локальные_переменные[имя_п] = rust_тип
            else:
                rust_params.append(f'_: {rust_тип}')

        тип_рез = self.тип_возврата_rust(объявл.результаты)

        if имя == 'main':
            вывод.write(f'fn main() {{\n')
        elif объявл.получатель:
            рец = объявл.получатель
            имя_рец = рец.имена[0] if рец.имена else '_self'
            тип_рец = self.тип_в_rust(рец.тип)
            вывод.write(f'impl {тип_рец} {{\n')
            вывод.write(f'    pub fn {имя}(&mut self{", " + ", ".join(rust_params) if rust_params else ""}){тип_рез} {{\n')
        else:
            params_str = ', '.join(rust_params)
            вывод.write(f'pub fn {имя}({params_str}){тип_рез} {{\n')

        self.тип_возврата_стек.append(объявл.результаты)

        if объявл.тело:
            for оп in объявл.тело.операторы:
                код = self.генерировать_оператор(оп, отступ=1)
                вывод.write(код)

        self.тип_возврата_стек.pop()

        if объявл.получатель:
            вывод.write('    }\n}\n\n')
        else:
            вывод.write('}\n\n')

        return вывод.getvalue()

    # ─── Глобальные объявления ───────────────────────────────────────────────

    def генерировать_глобальную_константу(self, объявл: ОбъявлениеКонстанты) -> str:
        рез = []
        for имя, знач in zip(объявл.имена, объявл.значения):
            if объявл.тип:
                rust_тип = self.тип_в_rust(объявл.тип)
            else:
                rust_тип = 'i64'
            val = self.генерировать_выражение(знач)
            рез.append(f'const {имя}: {rust_тип} = {val};\n')
        return ''.join(рез)

    def генерировать_глобальную_переменную_rust(self, объявл: ОбъявлениеПеременной) -> str:
        рез = []
        for имя in объявл.имена:
            rust_тип = self.тип_в_rust(объявл.тип) if объявл.тип else 'i64'
            if объявл.значения:
                val = self.генерировать_выражение(объявл.значения[0])
                рез.append(f'static mut {имя}: {rust_тип} = {val};\n')
            else:
                рез.append(f'static mut {имя}: {rust_тип} = 0;\n')
        return ''.join(рез)

    # ─── Операторы ───────────────────────────────────────────────────────────

    def отст(self, n: int) -> str:
        return '    ' * n

    def генерировать_оператор(self, оп, отступ=0) -> str:
        о = self.отст(отступ)

        if isinstance(оп, ОператорВозврата):
            if not оп.значения:
                return f'{о}return;\n'
            elif len(оп.значения) == 1:
                val = self.генерировать_выражение(оп.значения[0])
                return f'{о}return {val};\n'
            else:
                vals = ', '.join(self.генерировать_выражение(v) for v in оп.значения)
                return f'{о}return ({vals});\n'

        if isinstance(оп, ОператорВыражения):
            val = self.генерировать_выражение(оп.выражение)
            return f'{о}{val};\n'

        if isinstance(оп, ОператорКороткогоОбъявления):
            if len(оп.имена) == 1 and len(оп.значения) == 1:
                val = self.генерировать_выражение(оп.значения[0])
                имя = оп.имена[0]
                if имя == '_':
                    return f'{о}let _ = {val};\n'
                self.локальные_переменные[имя] = 'auto'
                return f'{о}let mut {имя} = {val};\n'
            else:
                рез = ''
                for имя, знач in zip(оп.имена, оп.значения):
                    val = self.генерировать_выражение(знач)
                    if имя == '_':
                        рез += f'{о}let _ = {val};\n'
                    else:
                        self.локальные_переменные[имя] = 'auto'
                        рез += f'{о}let mut {имя} = {val};\n'
                return рез

        if isinstance(оп, ОператорПрисваивания):
            if len(оп.цели) == 1 and len(оп.значения) == 1:
                цель = self.генерировать_выражение(оп.цели[0])
                val = self.генерировать_выражение(оп.значения[0])
                if оп.оператор == '=':
                    return f'{о}{цель} = {val};\n'
                else:
                    rust_op = оп.оператор
                    return f'{о}{цель} {rust_op} {val};\n'
            # Параллельное присваивание: а, б = б, а%б → через временные переменные
            if оп.оператор == '=' and len(оп.цели) > 1:
                рез = ''
                temps = []
                for i_т, з in enumerate(оп.значения):
                    tmp = f'_сбк_т{i_т}'
                    temps.append(tmp)
                    rval = self.генерировать_выражение(з)
                    рез += f'{о}let _сбк_т{i_т} = {rval};\n'
                for ц, tmp in zip(оп.цели, temps):
                    if not (isinstance(ц, Идентификатор) and ц.имя == '_'):
                        rname = self.генерировать_выражение(ц)
                        рез += f'{о}{rname} = {tmp};\n'
                return рез
            рез = ''
            for ц, з in zip(оп.цели, оп.значения):
                if not (isinstance(ц, Идентификатор) and ц.имя == '_'):
                    рез += f'{о}{self.генерировать_выражение(ц)} = {self.генерировать_выражение(з)};\n'
            return рез

        if isinstance(оп, ОператорИнкремента):
            val = self.генерировать_выражение(оп.выражение)
            # Rust не имеет ++ и -- — конвертируем
            оператор_сбк = оп.оператор if len(оп.оператор) >= 2 else '++'
            if оператор_сбк == '++':
                return f'{о}{val} += 1;\n'
            else:
                return f'{о}{val} -= 1;\n'

        if isinstance(оп, ОбъявлениеПеременной):
            рез = ''
            for i, имя in enumerate(оп.имена):
                if оп.тип:
                    rust_тип = self.тип_в_rust(оп.тип)
                    if оп.значения and i < len(оп.значения):
                        val = self.генерировать_выражение(оп.значения[i])
                        # Конвертация строковых литералов
                        if rust_тип == 'String':
                            val = f'{val}.to_string()'
                        рез += f'{о}let mut {имя}: {rust_тип} = {val};\n'
                    else:
                        рез += f'{о}let mut {имя}: {rust_тип} = Default::default();\n'
                else:
                    if оп.значения and i < len(оп.значения):
                        val = self.генерировать_выражение(оп.значения[i])
                        рез += f'{о}let mut {имя} = {val};\n'
                    else:
                        рез += f'{о}let mut {имя} = 0i64;\n'
                self.локальные_переменные[имя] = 'auto'
            return рез

        if isinstance(оп, ОбъявлениеКонстанты):
            рез = ''
            for имя, знач in zip(оп.имена, оп.значения):
                val = self.генерировать_выражение(знач)
                if оп.тип:
                    rust_тип = self.тип_в_rust(оп.тип)
                    рез += f'{о}let {имя}: {rust_тип} = {val};\n'
                else:
                    рез += f'{о}let {имя} = {val};\n'
            return рез

        if isinstance(оп, ОператорЕсли):
            усл = self.генерировать_выражение(оп.условие)
            рез = f'{о}if {усл} {{\n'
            for ст in оп.тогда.операторы:
                рез += self.генерировать_оператор(ст, отступ + 1)
            рез += f'{о}}}'
            if оп.иначе:
                if isinstance(оп.иначе, ОператорЕсли):
                    иначе_код = self.генерировать_оператор(оп.иначе, отступ).lstrip()
                    рез += f' else {иначе_код}'
                    return рез
                else:
                    рез += f' else {{\n'
                    for ст in оп.иначе.операторы:
                        рез += self.генерировать_оператор(ст, отступ + 1)
                    рез += f'{о}}}'
            рез += '\n'
            return рез

        if isinstance(оп, ОператорДля):
            if оп.тип_цикла == 'бесконечный':
                рез = f'{о}loop {{\n'
                for ст in оп.тело.операторы:
                    рез += self.генерировать_оператор(ст, отступ + 1)
                рез += f'{о}}}\n'
                return рез

            if оп.тип_цикла == 'диапазон':
                итер = self.генерировать_выражение(оп.итерируемое)
                ключ = оп.ключ if оп.ключ and оп.ключ != '_' else '_k'
                знач = оп.значение if оп.значение and оп.значение != '_' else '_v'
                рез = f'{о}for ({ключ}, {знач}) in {итер}.iter().enumerate() {{\n'
                рез += f'{о}    let {ключ} = {ключ} as i64;\n'
                for ст in оп.тело.операторы:
                    рез += self.генерировать_оператор(ст, отступ + 1)
                рез += f'{о}}}\n'
                return рез

            # Обычный for → Rust loop с меткой (post всегда выполняется)
            рез = f'{о}{{\n'
            if оп.инициализация:
                рез += self.генерировать_оператор(оп.инициализация, отступ + 1)
            усл = self.генерировать_выражение(оп.условие) if оп.условие else 'true'
            if оп.пост:
                пост_код = self.генерировать_оператор(оп.пост, 0).strip().rstrip(';')
                рез += f"{о}    'сбк_for: loop {{\n"
                рез += f'{о}        if !({усл}) {{ break; }}\n'
                for ст in оп.тело.операторы:
                    ст_код = self.генерировать_оператор(ст, отступ + 2)
                    ст_код = ст_код.replace('continue;', f'{пост_код}; continue;')
                    рез += ст_код
                рез += f'{о}        {пост_код};\n'
                рез += f"{о}    }}\n"
            else:
                рез += f'{о}    while {усл} {{\n'
                for ст in оп.тело.операторы:
                    рез += self.генерировать_оператор(ст, отступ + 2)
                рез += f'{о}    }}\n'
            рез += f'{о}}}\n'
            return рез
        if isinstance(оп, ОператорПереключить):
            # Всегда генерируем if-else для гибкости
            выр_сравн = self.генерировать_выражение(оп.выражение) if оп.выражение else None
            рез = ''
            первый = True
            for случай in оп.случаи:
                if not случай.выражения:
                    рез += f'{о}else {{\n'
                else:
                    условия = []
                    for выр_сл in случай.выражения:
                        с = self.генерировать_выражение(выр_сл)
                        if выр_сравн:
                            условия.append(f'{выр_сравн} == {с}')
                        else:
                            условия.append(с)
                    усл = ' || '.join(условия)
                    кл = 'if' if первый else 'else if'
                    рез += f'{о}{кл} {усл} {{\n'
                первый = False
                for ст in случай.тело:
                    рез += self.генерировать_оператор(ст, отступ + 1)
                рез += f'{о}}}\n'  
            return рез if рез else f'{о}// пустой перекл\n'

        if isinstance(оп, ОператорПрервать):
            return f'{о}break;\n'

        if isinstance(оп, ОператорПродолжить):
            return f'{о}continue;\n'

        if isinstance(оп, ОператорПерейти):
            # В Rust нет goto — используем метки циклов как заглушку
            return f'{о}// перейти {оп.метка} — не поддерживается в Rust напрямую\n'

        if isinstance(оп, ОператорМетки):
            вн = self.генерировать_оператор(оп.оператор, отступ)
            return f'{о}// метка: {оп.имя}\n{вн}'

        if isinstance(оп, БлокОператоров):
            рез = f'{о}{{\n'
            for ст in оп.операторы:
                рез += self.генерировать_оператор(ст, отступ + 1)
            рез += f'{о}}}\n'
            return рез

        if isinstance(оп, ОператорОтложить):
            # defer → простой вызов в конце (упрощённо)
            val = self.генерировать_выражение(оп.вызов)
            return f'{о}// отложить: {val} — выполнится при выходе из области\n'

        if isinstance(оп, ОператорГорутины):
            val = self.генерировать_выражение(оп.вызов)
            return f'{о}std::thread::spawn(move || {{ {val}; }});\n'

        return f'{о}// неизвестный оператор: {type(оп).__name__}\n'

    # ─── Выражения ───────────────────────────────────────────────────────────

    def генерировать_выражение(self, выр) -> str:
        if isinstance(выр, ЛитералЦелого):
            return f'{выр.значение}i64'

        if isinstance(выр, ЛитералВещественного):
            s = str(выр.значение)
            if '.' not in s:
                s += '.0'
            return f'{s}_f64'

        if isinstance(выр, ЛитералСтроки):
            экр = выр.значение.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t')
            return f'"{экр}"'

        if isinstance(выр, ЛитералРуны):
            c = выр.значение
            if c == "'":
                c = "\\'"
            elif c == '\\':
                c = '\\\\'
            return f"'{c}'"

        if isinstance(выр, ЛитералИстина):
            return 'true'

        if isinstance(выр, ЛитералЛожь):
            return 'false'

        if isinstance(выр, ЛитералНоль):
            return 'None'

        if isinstance(выр, Идентификатор):
            встроенные = {
                'длина': 'len',
                'паника': 'паника',
            }
            return встроенные.get(выр.имя, выр.имя)

        if isinstance(выр, БинарноеВыражение):
            л = self.генерировать_выражение(выр.левое)
            п = self.генерировать_выражение(выр.правое)
            # Rust использует те же операторы, кроме &&, ||
            оп_map = {'&&': '&&', '||': '||', '&^': '& !'}
            оп = оп_map.get(выр.оператор, выр.оператор)
            return f'({л} {оп} {п})'

        if isinstance(выр, УнарноеВыражение):
            операнд = self.генерировать_выражение(выр.операнд)
            if выр.оператор == '!':
                return f'(!{операнд})'
            if выр.оператор == '*':
                return f'(*{операнд})'
            if выр.оператор == '&':
                return f'(&{операнд})'
            if выр.оператор == '^':
                return f'(!{операнд})'  # bitwise NOT
            return f'({выр.оператор}{операнд})'

        if isinstance(выр, ВызовФункции):
            return self.генерировать_вызов(выр)

        if isinstance(выр, ДоступКПолю):
            объект = self.генерировать_выражение(выр.объект)
            return f'{объект}.{выр.поле}'

        if isinstance(выр, Индексирование):
            объект = self.генерировать_выражение(выр.объект)
            индекс = self.генерировать_выражение(выр.индекс)
            return f'{объект}[{индекс} as usize]'

        if isinstance(выр, Срезание):
            объект = self.генерировать_выражение(выр.объект)
            низ = self.генерировать_выражение(выр.низ) if выр.низ else '0i64'
            верх = self.генерировать_выражение(выр.верх) if выр.верх else f'{объект}.len() as i64'
            return f'{объект}[({низ} as usize)..({верх} as usize)].to_vec()'

        if isinstance(выр, ПреобразованиеТипа):
            rust_тип = self.тип_в_rust(выр.тип)
            операнд = self.генерировать_выражение(выр.выражение)
            # Строковое преобразование
            if rust_тип == 'String':
                return f'{операнд}.to_string()'
            if rust_тип in ('i64', 'i32', 'i8', 'u8', 'f64', 'f32'):
                return f'({операнд} as {rust_тип})'
            return f'({операнд} as {rust_тип})'

        if isinstance(выр, ЛитералСтруктуры):
            if выр.тип and isinstance(выр.тип, ПростойТип):
                имя = выр.тип.имя
                поля = []
                for поле in выр.поля:
                    val = self.генерировать_выражение(поле.значение)
                    if поле.ключ:
                        поля.append(f'{поле.ключ}: {val}')
                    else:
                        поля.append(val)
                return f'{имя} {{ {", ".join(поля)} }}'
            return '{}'

        if isinstance(выр, ВыражениеКанала):
            канал = self.генерировать_выражение(выр.канал)
            return f'{канал}.recv().unwrap()'

        if isinstance(выр, АнонимнаяФункция):
            params = ', '.join(
                f'{имя}: {self.тип_в_rust(п.тип)}'
                for п in выр.параметры for имя in (п.имена or ['_'])
            )
            тело_код = ''
            if выр.тело:
                for ст in выр.тело.операторы:
                    тело_код += self.генерировать_оператор(ст, 0).strip() + ' '
            return f'|{params}| {{ {тело_код.strip()} }}'

        return '0i64 /* неизвестное выражение */'

    def генерировать_вызов(self, выр: ВызовФункции) -> str:
        # Встроенные и пакетные вызовы
        if isinstance(выр.функция, Идентификатор):
            имя = выр.функция.имя

            if имя in ('печатьф', 'ПечатьФ', 'ВыводитьФ'):
                if not выр.аргументы:
                    return 'print!("")'
                fmt_str = self.генерировать_выражение(выр.аргументы[0])
                if len(выр.аргументы) == 1:
                    return f'print!({fmt_str})'
                аргументы = ', '.join(self.генерировать_выражение(а) for а in выр.аргументы[1:])
                return f'print!({fmt_str}, {аргументы})'

            if имя in ('печать', 'Печать', 'Вывести'):
                if not выр.аргументы:
                    return 'println!()'
                аргументы = ', '.join(self.генерировать_выражение(а) for а in выр.аргументы)
                if len(выр.аргументы) == 1:
                    return f'println!("{{}}", {аргументы})'
                части = ' '.join(['{}'] * len(выр.аргументы))
                return f'println!("{части}", {аргументы})'

            if имя == 'паника':
                if выр.аргументы:
                    msg = self.генерировать_выражение(выр.аргументы[0])
                    return f'паника({msg})'
                return 'паника("паника")'

            if имя == 'длина':
                if выр.аргументы:
                    а = self.генерировать_выражение(выр.аргументы[0])
                    return f'{а}.len() as i64'
                return '0i64'

            if имя == 'ёмкость':
                if выр.аргументы:
                    а = self.генерировать_выражение(выр.аргументы[0])
                    return f'{а}.capacity() as i64'
                return '0i64'

            if имя == 'создать':
                # создать([]цел, 0, 10) → Vec::with_capacity(10)
                if len(выр.аргументы) >= 2:
                    ёмк = self.генерировать_выражение(выр.аргументы[-1])
                    return f'Vec::with_capacity({ёмк} as usize)'
                return 'Vec::new()'

            if имя == 'добавить':
                if len(выр.аргументы) >= 2:
                    срез = self.генерировать_выражение(выр.аргументы[0])
                    эл = self.генерировать_выражение(выр.аргументы[1])
                    return f'{{ {срез}.push({эл}); {срез}.clone() }}'
                return 'vec![]'

            if имя == 'копировать':
                if len(выр.аргументы) >= 2:
                    dst = self.генерировать_выражение(выр.аргументы[0])
                    src = self.генерировать_выражение(выр.аргументы[1])
                    return f'{{ let _n = std::cmp::min({dst}.len(), {src}.len()); {dst}[.._n].copy_from_slice(&{src}[.._n]); _n as i64 }}'

            if имя == 'новый':
                if выр.аргументы and isinstance(выр.аргументы[0], Идентификатор):
                    тип = выр.аргументы[0].имя
                    return f'Box::new({тип}::default())'
                return 'Box::new(0i64)'

            if имя == 'удалить':
                if len(выр.аргументы) >= 2:
                    карта = self.генерировать_выражение(выр.аргументы[0])
                    ключ = self.генерировать_выражение(выр.аргументы[1])
                    return f'{карта}.remove(&{ключ})'

        # Доступ к методу пакета: фмт.Печать, ос.Выход и т.д.
        if isinstance(выр.функция, ДоступКПолю):
            объект = self.генерировать_выражение(выр.функция.объект)
            метод = выр.функция.поле
            аргументы = ', '.join(self.генерировать_выражение(а) for а in выр.аргументы)

            if isinstance(выр.функция.объект, Идентификатор):
                пакет = выр.функция.объект.имя

                if пакет == 'фмт':
                    if метод in ('Печать', 'Вывести', 'Println'):
                        if not выр.аргументы:
                            return 'println!()'
                        части = ' '.join(['{}'] * len(выр.аргументы))
                        return f'println!("{части}", {аргументы})'
                    if метод in ('ПечатьФ', 'ВыводитьФ', 'Printf'):
                        if not выр.аргументы:
                            return 'print!("")'
                        raw_fmt = выр.аргументы[0]
                        if isinstance(raw_fmt, ЛитералСтроки):
                            fmt_str = '"' + _конвертировать_формат(raw_fmt.значение).replace('"', '\\"') + '"'
                        else:
                            fmt_str = self.генерировать_выражение(raw_fmt)
                        if len(выр.аргументы) == 1:
                            return f'print!({fmt_str})'
                        остальные = ', '.join(self.генерировать_выражение(а) for а in выр.аргументы[1:])
                        return f'print!({fmt_str}, {остальные})'
                    if метод in ('Спринт', 'Sprintf', 'Форматировать'):
                        if выр.аргументы:
                            raw_fmt = выр.аргументы[0]
                            if isinstance(raw_fmt, ЛитералСтроки):
                                fmt_str = '"' + _конвертировать_формат(raw_fmt.значение).replace('"', '\\"') + '"'
                            else:
                                fmt_str = self.генерировать_выражение(raw_fmt)
                            if len(выр.аргументы) == 1:
                                return f'format!({fmt_str})'
                            остальные = ', '.join(self.генерировать_выражение(а) for а in выр.аргументы[1:])
                            return f'format!({fmt_str}, {остальные})'
                    if метод in ('Скан', 'Считать', 'Scan'):
                        return f'/* скан: не реализовано */'

                if пакет == 'ос':
                    if метод in ('Выход', 'Exit'):
                        return f'std::process::exit({аргументы} as i32)'
                    if метод == 'Аргументы':
                        return 'std::env::args().collect::<Vec<_>>()'

                if пакет == 'математика':
                    матем = {
                        'Корень': 'f64::sqrt', 'Степень': 'f64::powf',
                        'Абс': 'f64::abs', 'Синус': 'f64::sin',
                        'Косинус': 'f64::cos', 'Тангенс': 'f64::tan',
                        'Логарифм': 'f64::ln', 'Логарифм10': 'f64::log10',
                        'Пол': 'f64::floor', 'Потолок': 'f64::ceil',
                        'Округл': 'f64::round', 'Макс': 'f64::max',
                        'Мин': 'f64::min',
                    }
                    if метод in матем:
                        аргс = [self.генерировать_выражение(а) for а in выр.аргументы]
                        if len(аргс) == 1:
                            return f'({аргс[0]}).{метод.lower()}()'
                        elif len(аргс) == 2:
                            return f'({аргс[0]}).{["powf","max","min","log"][0]}({аргс[1]})'

                if пакет == 'строки':
                    str_методы = {
                        'Содержит': 'contains', 'НачинаетсяС': 'starts_with',
                        'ЗаканчиваетсяНа': 'ends_with', 'Верхний': 'to_uppercase',
                        'Нижний': 'to_lowercase', 'Обрезать': 'trim',
                        'Разделить': 'split',
                    }
                    if метод in str_методы:
                        аргс = [self.генерировать_выражение(а) for а in выр.аргументы]
                        if аргс:
                            return f'{аргс[0]}.{str_методы[метод]}({", ".join(аргс[1:])})'

            # Обычный вызов метода объекта
            return f'{объект}.{метод}({аргументы})'

        # Обычный вызов функции
        функция = self.генерировать_выражение(выр.функция)
        аргументы = ', '.join(self.генерировать_выражение(а) for а in выр.аргументы)
        return f'{функция}({аргументы})'
